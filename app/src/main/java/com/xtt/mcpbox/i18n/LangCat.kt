    /** 翻译成猫娘语：有特殊说法就用，没有就加个「喵」。 */
    fun say(zh: String): String {
        SPECIAL[zh]?.let { return it }
        // 已经很喵了就不要再叠
        if (zh.endsWith("喵") || zh.endsWith("喵～")) return zh
        // 纯符号 / 空的就别动
        if (zh.isBlank()) return zh
        return when {
            zh.endsWith("！") || zh.endsWith("!") -> zh.dropLast(1) + "喵！"
            zh.endsWith("。") -> zh.dropLast(1) + "喵。"
            zh.endsWith("…") -> zh + "喵…"
            zh.endsWith("？") || zh.endsWith("?") -> zh.dropLast(1) + "喵？"
            else -> zh + "喵"
        }
    }
